board = [" "] * 9

#Draw the board
def show_board():
  print(board[0]+"  |"+board[1]+'  |'+board[2])
  print("___+___+___")
  print(board[3]+"  |"+board[4]+"  |"+board[5])
  print("___+___+___")
  print(board[6]+"  |"+board[7]+"  |"+board[8])

# recognize the winner
avilable = []
def define_winner():
  avilable.clear()
  winner = [[0,1,2],[3,4,5],[6,7,8],
         [0,3,6],[1,4,7],[2,5,8],
         [0,4,8],[2,4,6]]
  # make a curser that goes to each board and check if it is empty or not

  for i in range(0, 9, 1):
    if board[i] == " ":
      avilable.append(i)
  for i in winner:
    a,b,c = i
    if board[a] == board[b] == board[c] != " ":
      return board[a]
  return None

# adjust players and make the system and put there x and o on the grid
define_winner()
while True:
  player_1 = int(input("Player 1: ")) - 1
  print()
  if player_1 in avilable:
    board[player_1] = "X"
  show_board()
  print("----------------------")
  player_2 = int(input("Player 2: ")) - 1
  print()
  if player_2 in avilable:
    board[player_2] = "O"
  show_board()
  print("----------------------")
  for i in range(0, 9, 1):
    if define_winner() == "X":
      print("Player 1 wins")
      break
    if define_winner() == "O":
      print("Player 2 wins")
      break



  if define_winner() == None and len(avilable) == 0:
    print("Draw")
    break